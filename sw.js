// 🔔 الإشعارات خارج التطبيق (Web Push)
// ------------------------------------------------------------
// الـ service worker ده بيفضل شغّال حتى والتطبيق مقفول — وده
// السبب الوحيد اللي بيخلّي الإشعار يوصل وإنت برّه التطبيق.
// السيرفر بيبعت الرسالة **له هو**، مش للصفحة.
//
// ⚠️ userVisibleOnly=true في الاشتراك معناها وعد للمتصفح:
//    «كل رسالة توصل، هطلّع منها إشعار مرئي». لو استقبلنا رسالة
//    وما طلّعناش إشعار، المتصفح بيلغي الاشتراك بعد كام مرة.
//    عشان كده showNotification بتتنده **دايماً**، حتى لو البيانات
//    جت بايظة — بنطلّع رسالة عامة بدل ما نسكت.
//
// 🚀🚀🚀 (المرحلة ٣ — notify-push) الرسالة فيها كمان dev = رقم الجهاز،
//    عشان الدوس على الإشعار يفتح الجهاز نفسه.
// ============================================================
self.addEventListener('push', (event) => {
  let d = {};
  try{ d = event.data ? event.data.json() : {}; }catch(e){ d = {}; }

  const title = d.title || 'تحديث جديد';
  const opts  = {
    body:  d.body || 'افتح التطبيق للتفاصيل',
    icon:  'icon-192.png',
    badge: 'icon-192.png',
    dir:   'rtl',
    lang:  'ar',
    // tag واحد = الإشعار الجديد بيستبدل القديم بدل ما يتكوّم ٢٠ إشعار
    // (إشعارات الأجهزة: tag = ifx-<رقم الجهاز> — نفس تنبيه المرحلة الأولى
    //  جوه التطبيق، فمايطلعوش الاتنين فوق بعض)
    tag:   d.tag || 'ifix-payroll',
    renotify: true,
    data:  { url: d.url || 'index.html', dev: d.dev || null }
  };
  event.waitUntil(self.registration.showNotification(title, opts));
});

// ============================================================
// الدوس على الإشعار
// ------------------------------------------------------------
// ⚠️ لو التطبيق مفتوح في الخلفية، بنركّز عليه بدل ما نفتح تبويب
//    جديد. من غير الفحص ده الموظف بيلاقي نسختين من التطبيق
//    مفتوحين — وفي وضع الشاشة الرئيسية النسخة الجديدة مالهاش
//    زرار رجوع خالص.
// 🚀🚀🚀 ولو الإشعار عن جهاز: بنقول للصفحة المفتوحة «افتحي الجهاز ده»
//    (dashboard.html بتسمع على ifx-open-dev). التطبيق مقفول؟ بيفتح
//    على dashboard.html?dev=… والصفحة بتفتحه لوحدها.
// ============================================================
self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const data   = event.notification.data || {};
  const target = data.url || 'index.html';
  const dev    = data.dev || null;
  const isChat = /^ifx-chat/.test(event.notification.tag || '');
  // 🧭 الصفحة اللي الإشعار عايزها (my-devices.html / dispatch.html / …)
  const page   = (target.split('?')[0].split('/').pop() || 'index.html').toLowerCase();
  event.waitUntil(
    self.clients.matchAll({ type:'window', includeUncontrolled:true }).then(list => {
      const mine = list.filter(c => c.url.indexOf(self.location.origin) === 0);
      const pathOf = c => (new URL(c.url).pathname.split('/').pop() || 'index.html').toLowerCase();
      // 💬 الشات موجود في كل الشاشات → أي شاشة مفتوحة تنفع
      if(isChat){
        const any = mine[0];
        if(any && 'focus' in any){
          try{ any.postMessage({ type:'ifx-open-chat' }); }catch(e){}
          return any.focus();
        }
        return self.clients.openWindow(target);
      }
      // 🔧 جهاز: الأولوية للشاشة نفسها لو مفتوحة
      const same = mine.find(c => pathOf(c) === page)
                || (page === 'index.html' ? mine[0] : null);
      if(same && 'focus' in same){
        if(dev){ try{ same.postMessage({ type:'ifx-open-dev', id: dev }); }catch(e){} }
        return same.focus();
      }
      // الشاشة مش مفتوحة → نفتحها (مش بنحوّل شاشة مفتوحة عشان مايضيعش شغل مكتوب فيها)
      return self.clients.openWindow(target);
    })
  );
});
